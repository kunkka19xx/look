#!/usr/bin/env python3
"""Regenerates ../src/data.rs from Unicode emoji-test.txt (order, glyphs) and
CLDR annotations en.xml (names, keywords).

    curl -fL -o /tmp/en.xml https://raw.githubusercontent.com/unicode-org/cldr/main/common/annotations/en.xml
    curl -fL -o /tmp/emoji-test.txt https://unicode.org/Public/emoji/latest/emoji-test.txt
    python3 gen_data.py /tmp/emoji-test.txt /tmp/en.xml > ../src/data.rs

Skin-tone variants are skipped (out of scope for v1).
"""

import re
import sys
import xml.etree.ElementTree as ET

FE0F = "\ufe0f"


def norm(s):
    return s.replace(FE0F, "")


def rust_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main(test_path, xml_path):
    version = re.search(r"# Version: (\S+)", open(test_path, encoding="utf-8").read()).group(1)

    names, keywords = {}, {}
    for a in ET.parse(xml_path).getroot().iter("annotation"):
        cp = norm(a.get("cp"))
        if a.get("type") == "tts":
            names[cp] = a.text
        else:
            keywords[cp] = [k.strip() for k in a.text.split("|") if k.strip()]

    entries, seen = [], set()
    group = None
    for line in open(test_path, encoding="utf-8"):
        if line.startswith("# group:"):
            group = line.split(":", 1)[1].strip()
            continue
        if group == "Component" or "; fully-qualified" not in line:
            continue
        glyph = line.split(";")[0].strip()
        glyph = "".join(chr(int(c, 16)) for c in glyph.split())
        key = norm(glyph)
        name = names.get(key)
        if name is None or "skin tone" in name or key in seen:
            continue
        seen.add(key)
        entries.append((glyph, name, keywords.get(key, [])))

    out = [
        "// @generated by tools/gen_data.py - do not edit.",
        f"// Sources: Unicode emoji-test.txt v{version}; CLDR annotations en.xml",
        "// (Unicode License v3, https://www.unicode.org/license.txt).",
        "",
        "use crate::Emoji;",
        "",
        "pub(crate) static EMOJI: &[Emoji] = &[",
    ]
    for glyph, name, kws in entries:
        k = ", ".join(rust_str(x) for x in kws)
        out.append(
            f"    Emoji {{ glyph: {rust_str(glyph)}, name: {rust_str(name)}, keywords: &[{k}] }},"
        )
    out.append("];")
    print("\n".join(out))
    print(f"generated {len(entries)} emoji", file=sys.stderr)


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
